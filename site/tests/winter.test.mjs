import {test,expect} from '@playwright/test';
const URL='/mandats/france/hiver/';
const KEY='mandats.winter.v1';
async function noOverflow(page){expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);}
test('two winters: choices persist, reshape the scene and preserve the complete mandate',async({page},info)=>{
 await page.goto('/mandats/');await page.getByRole('link',{name:/Deux hivers/}).click();
 await expect(page.locator('h1')).toHaveText('Le froid arrive. Qui protéger ?');
 await expect.poll(()=>page.locator('.winter-stage-image').evaluate(i=>i.complete&&i.naturalWidth>0)).toBe(true);
 await noOverflow(page);await page.screenshot({path:test.info().outputPath('winter-first-'+info.project.name+'.png'),fullPage:true});
 await page.locator('[data-choice="chauffer"]').click();
 await expect(page.locator('.winter-stage')).toHaveAttribute('data-warmth','0.720');
 await expect(page.locator('.winter-stage')).toHaveAttribute('data-activity','0.440');
 await expect(page.locator('h1')).toBeFocused();await page.reload();
 await expect(page.locator('.winter-decision-top')).toContainText('2/3');
 await page.locator('[data-choice="isoler"]').click();
 await expect(page.locator('.winter-stage')).toHaveAttribute('data-renovated','true');
 await expect(page.locator('.winter-stage')).toHaveAttribute('data-season','winter-return');
 await expect(page.locator('[data-choice="foyers"]')).toBeDisabled();
 await expect(page.locator('.winter-reserve')).toContainText('6');
 await page.locator('[data-choice="sobriete"]').click();
 await expect(page.locator('h1')).toHaveText('Des logements mieux préparés');
 await expect(page.getByRole('link',{name:'Jouer le mandat de 45 décisions'})).toBeVisible();
 expect(await page.evaluate(key=>JSON.parse(localStorage.getItem(key)).choices,KEY)).toEqual(['chauffer','isoler','sobriete']);
 expect(await page.evaluate(()=>localStorage.getItem('500signatures.mandats.v1'))).toBeNull();
 await noOverflow(page);await page.screenshot({path:test.info().outputPath('winter-result-'+info.project.name+'.png'),fullPage:true});
 await page.getByRole('button',{name:'Essayer une autre stratégie'}).click();
 await expect(page.locator('.winter-reserve')).toContainText('60');
});
test('the living scene moves, pauses and respects reduced motion',async({page})=>{
 await page.goto(URL);const person=page.locator('[data-person="0"]');
 const first=await person.getAttribute('transform');
 await expect.poll(()=>person.getAttribute('transform')).not.toBe(first);
 await page.getByRole('button',{name:'Pause',exact:true}).click();
 await expect(page.locator('.winter-stage')).toHaveAttribute('data-animation-paused','true');
 const paused=await person.getAttribute('transform');
 // Keep interacting with the page while animation is stopped.
 await page.getByRole('button',{name:'Règles et sauvegarde'}).click();
 await expect(page.getByRole('dialog')).toBeVisible();
 await page.getByRole('button',{name:'Fermer',exact:true}).click();
 expect(await person.getAttribute('transform')).toBe(paused);
 await page.getByRole('button',{name:'Animer',exact:true}).click();
 await expect.poll(()=>person.getAttribute('transform')).not.toBe(paused);
 await page.emulateMedia({reducedMotion:'reduce'});
 await expect(page.locator('.winter-stage')).toHaveAttribute('data-animation-paused','true');
 await page.locator('[data-choice="produire"]').click();
 await expect(page.locator('.winter-stage')).toHaveAttribute('data-activity','0.720');
 await expect(page.locator('#work-signal')).toContainText('préservés');await noOverflow(page);
});
